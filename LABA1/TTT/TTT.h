#ifndef TTT_H
#define TTT_H

#include <iostream>
#include <string>

/**
 * @brief Класс игры "Крестики-нолики" (Tic-Tac-Toe).
 *
 * Реализует консольную игру для двух игроков на поле 3x3.
 * Игрок A играет символом 'O', игрок B — символом 'X'.
 *
 * @note Поле хранится как двумерный массив символов @c char[3][3].
 * @warning Класс не поддерживает игру против компьютера.
 */
class TTT
{
public:
    /**
     * @brief Запуск игрового процесса.
     *
     * Последовательно выполняет:
     * 1. Очистку поля.
     * 2. Ввод имён игроков.
     * 3. Отображение поля.
     * 4. Цикл ходов до победы одного из игроков.
     * 5. Объявление победителя.
     */
    void game();

private:
    std::string playerA;    ///< Имя игрока A (ходит первым, символ 'O')
    std::string playerB;    ///< Имя игрока B (ходит вторым, символ 'X')
    char field[3][3];       ///< Игровое поле 3x3

    /**
     * @brief Запрос координат хода у игрока.
     *
     * В цикле запрашивает у пользователя координаты ячейки
     * до тех пор, пока они не окажутся в пределах поля.
     *
     * @param[out] x указатель на строку (0–2)
     * @param[out] y указатель на столбец (0–2)
     *
     * @pre x и y — валидные указатели на int.
     */
    void chp(int* x, int* y);

    /**
     * @brief Отображение игрового поля в консоли.
     * @param[in] field отображаемое поле 3x3
     */
    void showf(char field[3][3]);

    /**
     * @brief Проверка условия победы.
     *
     * Проверяет все 8 линий (3 строки, 3 столбца, 2 диагонали)
     * на наличие трёх одинаковых непробельных символов.
     *
     * @param[in] field проверяемое поле 3x3
     * @return @c true, если кто-то победил, иначе @c false
     */
    bool win(char field[3][3]);
};

#endif // TTT_H
